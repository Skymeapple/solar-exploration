"""Write the campaign results as Markdown and JSON."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np


def _row(cells) -> str:
    return "| " + " | ".join(str(c) for c in cells) + " |"


def to_markdown(o: dict) -> str:
    L = ["# Mars sample return: end-to-end simulation and verification", ""]
    L += ["Generated by `python -m sample_return`. Tags: [cited] public source, [memory] public figure not re-checked, "
          "[estimate] study assumption. See `src/sample_return/references.py`.", ""]
    L += ["## Verification gates", "", _row(["Gate", "Phase", "Result", "Evidence"]), _row(["---"] * 4)]
    for g in o["gates"]:
        L.append(_row([g.id, g.phase, "PASS" if g.passed else "FAIL", g.detail]))
    t = o["transfer"]
    L += ["", "## Timeline", "", _row(["Event", "Date", "Note"]), _row(["---"] * 3)]
    L.append(_row(["Lander + MAV launch", t["outbound"].depart_date, f"C3 {t['outbound'].c3_depart:.1f} km2/s2"]))
    L.append(_row(["Mars arrival", t["outbound"].arrive_date, f"{t['outbound'].tof_days:.0f} days"]))
    L.append(_row(["MAV launch, OS capture, CV sealing", "before " + t["return"].depart_date, "orbiter waits in 380 km orbit"]))
    L.append(_row(["Trans-Earth burn", t["return"].depart_date, f"{o['return']['tei_dv']:.0f} m/s"]))
    L.append(_row(["EEV entry and landing", t["return"].arrive_date, f"{o['return']['entry_speed'] / 1e3:.2f} km/s"]))
    a = o["ascent"]
    mav, nom, mc = a["mav"], a["nominal"], a["monte_carlo"]
    L += ["", "## Mars ascent vehicle", "", _row(["Quantity", "Value"]), _row(["---"] * 2)]
    for k, v in [
        ("Gross mass", f"{mav.gross_mass:.0f} kg"),
        ("Stage 1 propellant / inert", f"{mav.stage1.propellant:.0f} / {mav.stage1.inert:.0f} kg, {mav.stage1.burn_time:.0f} s burn"),
        ("Stage 2 propellant / inert", f"{mav.stage2.propellant:.1f} / {mav.stage2.inert:.0f} kg, {mav.stage2.burn_time:.0f} s burn"),
        ("Payload (OS + adapter)", f"{mav.payload:.1f} kg"),
        ("Pitch rate (solved)", f"{mav.pitch_rate:.3f} deg/s"),
        ("Stage-1 burnout altitude", f"{nom.burnout1_alt / 1e3:.0f} km"),
        ("Coast to stage-2 ignition", f"{nom.coast_time:.0f} s"),
        ("Orbit", f"{nom.periapsis_alt / 1e3:.0f} x {nom.apoapsis_alt / 1e3:.0f} km"),
        ("Ideal / delivered dv", f"{nom.ideal_dv:.0f} / {nom.delivered_dv:.0f} m/s"),
        ("Max dynamic pressure", f"{nom.max_q:.0f} Pa"),
        ("Max acceleration", f"{nom.max_accel_g:.1f} g"),
    ]:
        L.append(_row([k, v]))
    s = mc.summary()
    L += ["", "Design iteration on orbit dispersion (share of runs with periapsis above the floor):", ""]
    L += [f"- {lab}: {frac * 100:.1f} %" for lab, frac in a["iterations"]]
    L += ["", f"Final Monte Carlo ({s['runs']} runs): mean periapsis {s['periapsis_mean_km']:.0f} km, "
          f"3-sigma low {s['periapsis_3sigma_low_km']:.0f} km, mean apoapsis {s['apoapsis_mean_km']:.0f} km, "
          f"semi-major-axis sigma {s['sma_sigma_km']:.1f} km."]
    r = o["rendezvous"]
    ap = r["approach"].summary()
    L += ["", "## Rendezvous and capture", "",
          f"- Orbit matching dv: mean {r['match_dv'].mean():.0f} m/s, p99 {np.percentile(r['match_dv'], 99):.0f} m/s",
          f"- Terminal approach ({ap['runs']} runs): capture {ap['p_capture'] * 100:.2f} %, dv mean {ap['dv_mean_m_s']:.1f} m/s, "
          f"p99 {ap['dv_p99_m_s']:.1f} m/s, lateral miss p99 {ap['final_miss_p99_m'] * 100:.1f} cm",
          f"- CW vs nonlinear two-body, 10 km hop: {r['cw_miss_m']:.1f} m"]
    e = o["entry"]
    n, sd = e["nominal"], e["stardust"]
    fp = e["footprint"].summary()
    L += ["", "## Earth entry", "", _row(["Case", "Entry speed", "Peak heat flux", "Peak decel", "Heat load", "Impact"]),
          _row(["---"] * 6)]
    L.append(_row(["MSR-class EEV (nominal)", f"{o['return']['entry_speed'] / 1e3:.2f} km/s", f"{n.peak_heat_flux / 1e4:.0f} W/cm2",
                   f"{n.peak_decel_g:.0f} g", f"{n.heat_load / 1e7:.1f} kJ/cm2", f"{n.impact_speed:.1f} m/s, {n.impact_g:.0f} g"]))
    L.append(_row(["Stardust reference", "12.90 km/s [cited]", f"{sd.peak_heat_flux / 1e4:.0f} W/cm2", f"{sd.peak_decel_g:.0f} g",
                   f"{sd.heat_load / 1e7:.1f} kJ/cm2", "parachute"]))
    L += ["", f"Footprint ({fp['runs']} runs): 3-sigma downrange {fp['downrange_3sigma_km']:.1f} km; "
          f"impact load p99 {fp['impact_g_p99']:.0f} g; peak heat p99 {fp['peak_heat_p99_W_cm2']:.0f} W/cm2. "
          "Convective heating only (Sutton-Graves)."]
    c = o["containment"]
    L += ["", "## Containment (probability of release)", "", _row(["Path", "Probability"]), _row(["---"] * 2)]
    for k, v in c.paths.items():
        L.append(_row([k, f"{v:.1e}"]))
    L.append(_row(["**Total**", f"**{c.total:.1e}** (requirement < 1e-6)"]))
    L += ["", "## Cross-target comparison", "",
          _row(["Target", "C3 out (km2/s2)", "v_inf arrive (km/s)", "One way (days)", "Ascent dv (m/s)", "Entry (km/s)",
                "EEV peak heat (W/cm2)", "Peak decel (g)", "PP category", "Heritage"]),
          _row(["---"] * 10)]
    for t in o["targets"]:
        L.append(_row([t.name, f"{t.c3_depart:.1f}", f"{t.vinf_arrive:.2f}", f"{t.one_way_days:.0f}", f"{t.ascent_dv:.0f}",
                       f"{t.entry_speed:.2f}", f"{t.peak_heat_W_cm2:.0f}", f"{t.peak_decel_g:.0f}", t.pp_category, t.heritage]))
    L += ["", "Transfers are circular-coplanar Hohmann estimates; outer-planet missions use gravity assists, "
          "so their real C3 and flight times differ."]
    return "\n".join(L) + "\n"


def to_json(o: dict) -> dict:
    t, a = o["transfer"], o["ascent"]
    return {
        "gates": [{"id": g.id, "phase": g.phase, "passed": g.passed, "detail": g.detail} for g in o["gates"]],
        "outbound": {"depart": t["outbound"].depart_date, "arrive": t["outbound"].arrive_date, "c3": t["outbound"].c3_depart},
        "return": {"depart": t["return"].depart_date, "arrive": t["return"].arrive_date,
                   "tei_dv": o["return"]["tei_dv"], "entry_speed": o["return"]["entry_speed"]},
        "mav": {"gross_kg": a["mav"].gross_mass, "stage2_prop_kg": a["mav"].stage2.propellant, "pitch_rate": a["mav"].pitch_rate,
                "ascent_mc": a["monte_carlo"].summary(), "iterations": a["iterations"]},
        "rendezvous": {"cw_miss_m": o["rendezvous"]["cw_miss_m"], "dv_p99": o["rendezvous"]["dv_p99"],
                       "approach": o["rendezvous"]["approach"].summary()},
        "entry": {"peak_heat_W_cm2": o["entry"]["nominal"].peak_heat_flux / 1e4, "peak_decel_g": o["entry"]["nominal"].peak_decel_g,
                  "footprint": o["entry"]["footprint"].summary()},
        "containment": {**o["containment"].paths, "total": o["containment"].total},
        "collection": o["collection"],
        "targets": [t.__dict__ for t in o["targets"]],
    }


def write(o: dict, outdir: str | Path) -> tuple[Path, Path]:
    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    md = outdir / "summary.md"
    js = outdir / "results.json"
    md.write_text(to_markdown(o))
    js.write_text(json.dumps(to_json(o), indent=2, default=float))
    return md, js
