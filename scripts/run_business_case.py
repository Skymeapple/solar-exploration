"""Run the business case and write results/business/."""
from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from raptor_sim.econ import inputs as I  # noqa: E402
from raptor_sim.econ.costs import VehicleCost, engine_cost, missions  # noqa: E402
from raptor_sim.econ.plan import (BASE, ROUNDS, SCENARIOS, cap_table, cash_balance,  # noqa: E402
                                  project, tornado, value)

OUT = ROOT / "results" / "business"


def m(x: float) -> str:
    return f"{x / 1e6:,.2f}"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    eng = engine_cost()
    with open(OUT / "engine_cost.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["part_number", "name", "assembly", "mass_kg", "material_usd", "labour_usd", "purchased_usd", "t1_usd"])
        for p in eng.parts:
            w.writerow([p.part, p.name, p.assembly, round(p.mass_kg, 1), round(p.material_usd), round(p.labour_usd),
                        round(p.purchased_usd), round(p.total)])

    vc = VehicleCost(eng)
    lines = ["# Business case results", "",
             "Generated by `scripts/run_business_case.py`. Money in 2026 US$. Basis tags and sources are in "
             "`src/raptor_sim/econ/inputs.py`.", "",
             "## Engine unit cost from the BOM (estimate)", "",
             "| Assembly | T1 cost ($M) |", "| --- | ---: |"]
    for a, c in sorted(eng.by_assembly().items()):
        lines.append(f"| {a} | {m(c)} |")
    lines += [f"| Assembly and acceptance test | {m(eng.t1_test)} |", f"| **Total, first unit** | **{m(eng.t1)}** |", "",
              "| Unit number | Cost ($M) |", "| ---: | ---: |"]
    for n in (1, 10, 100, 1000, 4000):
        lines.append(f"| {n} | {m(eng.unit(n))} |")

    lines += ["", f"## Mature vehicle and flight cost (vehicle unit {I.FLEET_UNIT_INDEX}, engine unit {I.ENGINE_UNIT_INDEX})", "",
              f"Booster ${m(vc.booster())}M, ship ${m(vc.ship())}M.", "", "| Per-flight item | $M |", "| --- | ---: |"]
    for k, v in vc.flight_breakdown().items():
        lines.append(f"| {k} | {m(v)} |")
    lines.append(f"| **Total, reusable flight** | **{m(vc.flight_cost())}** |")

    lines += ["", "## Per-mission cost at maturity", "", "| Mission | Flights | Cost ($M) | $/kg delivered |",
              "| --- | ---: | ---: | ---: |"]
    mis = []
    for pay in (I.MODEL["payload_leo_stated_t"], I.MODEL["payload_leo_model_t"]):
        for ms in missions(vc, pay):
            if ms.name.startswith("LEO") or pay == I.MODEL["payload_leo_stated_t"]:
                label = ms.name + (f" ({pay:.0f} t)" if ms.name.startswith("LEO") else "")
                lines.append(f"| {label} | {ms.flights} | {m(ms.cost)} | {ms.usd_per_kg:,.0f} |")
                mis.append({"mission": label, "flights": ms.flights, "cost_musd": ms.cost / 1e6, "usd_per_kg": ms.usd_per_kg})

    lines += ["", "## Scenarios, 2027-2041", "",
              "| Scenario | NPV at 12% ($M) | IRR | Cash trough ($M) | Trough year | Cumulative payback | 2041 revenue ($M) | 2041 free cash flow ($M) |",
              "| --- | ---: | ---: | ---: | ---: | --- | ---: | ---: |"]
    summary = {}
    for s in SCENARIOS:
        v = value(s)
        lines.append(f"| {s.name} | {v.npv_musd:,.0f} | {v.irr * 100 if v.irr is not None else float('nan'):.0f}% | "
                     f"{v.trough_musd:,.0f} | {v.trough_year} | {v.payback_year or 'not by 2041'} | {v.revenue_2041:,.0f} | {v.fcf_2041:,.0f} |")
        summary[s.name] = {"npv_musd": v.npv_musd, "irr": v.irr, "terminal_musd": v.terminal_musd,
                           "trough_musd": v.trough_musd, "trough_year": v.trough_year, "payback_year": v.payback_year,
                           "revenue_2041": v.revenue_2041, "fcf_2041": v.fcf_2041,
                           "cash_with_rounds": cash_balance(s)}

    with open(OUT / "plan_by_year.csv", "w", newline="") as f:
        w = csv.writer(f)
        rows = {s.name: project(s) for s in SCENARIOS}
        rev_keys = list(rows["Base"][0].revenue)
        cost_keys = list(rows["Base"][0].cost)
        w.writerow(["scenario", "year", "flights"] + rev_keys + cost_keys + ["tax", "revenue_total", "cost_total", "fcf"])
        for name, rs in rows.items():
            for r in rs:
                w.writerow([name, r.year, round(r.flights, 1)] + [round(r.revenue[k], 1) for k in rev_keys]
                           + [round(r.cost[k], 1) for k in cost_keys] + [round(r.tax, 1), round(r.revenue_total, 1),
                                                                         round(r.cost_total, 1), round(r.fcf, 1)])

    lines += ["", "## Base case by year ($M)", "", "| Year | Flights | Revenue | Cost | Free cash flow | Cash with financing plan |",
              "| --- | ---: | ---: | ---: | ---: | ---: |"]
    bal = dict(cash_balance(BASE))
    for r in project(BASE):
        lines.append(f"| {r.year} | {r.flights:.0f} | {r.revenue_total:,.0f} | {r.cost_total:,.0f} | {r.fcf:,.0f} | {bal[r.year]:,.0f} |")

    tor = tornado()
    lines += ["", "## Sensitivity of base NPV ($M change)", "", "| Driver | Downside | Upside |", "| --- | ---: | ---: |"]
    for label, lo, hi, _ in tor:
        lines.append(f"| {label} | {lo:,.0f} | {hi:,.0f} |")

    lines += ["", "## Financing plan (estimate)", "", "| Round | Year | Raise ($M) | Pre-money ($M) | Founders after | Milestone |",
              "| --- | ---: | ---: | ---: | ---: | --- |"]
    for rd, h in cap_table():
        pre = f"{rd.pre_money_musd:,.0f}" if rd.pre_money_musd else "debt"
        lines.append(f"| {rd.name} | {rd.year} | {rd.raise_musd:,.0f} | {pre} | {h['Founders'] * 100:.0f}% | {rd.milestone} |")

    (OUT / "summary.md").write_text("\n".join(lines) + "\n")
    (OUT / "business_case.json").write_text(json.dumps({
        "engine_t1_usd": eng.t1, "engine_unit_usd": {n: eng.unit(n) for n in (1, 10, 100, 1000, 4000)},
        "booster_usd": vc.booster(), "ship_usd": vc.ship(), "flight_breakdown_usd": vc.flight_breakdown(),
        "missions": mis, "scenarios": summary,
        "tornado": [{"driver": t[0], "downside_musd": t[1], "upside_musd": t[2]} for t in tor],
        "sources": I.SOURCES}, indent=2, default=float))
    print((OUT / "summary.md").read_text())


if __name__ == "__main__":
    main()
