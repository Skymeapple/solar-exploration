"""Run the lunar transit base study and write results/lunar_base/.

    python scripts/run_lunar_base.py            # tables, JSON, provenance
    python scripts/run_lunar_base.py --plots    # also PNG figures (needs matplotlib)
"""

from __future__ import annotations

import argparse
import csv
import json
import math
from pathlib import Path

import numpy as np

from raptor_sim.lunar_base import (
    buildup, checks, construction, depot, isru, mars_benefit, orbits, plume, power, reuse, site,
)
from raptor_sim.lunar_base import provenance

OUT = Path(__file__).resolve().parents[1] / "results" / "lunar_base"


def f(x, nd=0):
    if isinstance(x, (float, np.floating)):
        if math.isinf(x):
            return "beyond orbit"
        return f"{x:,.{nd}f}"
    return str(x)


def md_table(rows: list[dict], cols: list[tuple[str, str, int]]) -> str:
    head = "| " + " | ".join(c[1] for c in cols) + " |\n|" + "|".join(" --- " for _ in cols) + "|\n"
    body = "".join("| " + " | ".join(f(r[c[0]], c[2]) for c in cols) + " |\n" for r in rows)
    return head + body


def jsonable(o):
    if isinstance(o, dict):
        return {k: jsonable(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [jsonable(v) for v in o]
    if isinstance(o, (np.floating, np.integer)):
        return float(o)
    if isinstance(o, np.bool_):
        return bool(o)
    if isinstance(o, float) and math.isinf(o):
        return None
    return o


def main(plots: bool) -> dict:
    OUT.mkdir(parents=True, exist_ok=True)
    res: dict = {}
    md: list[str] = ["# Lunar transit base: study results\n",
                     "Generated by `scripts/run_lunar_base.py`. Every input carries a provenance tag "
                     "(cited, computed or estimated); see `provenance.csv`.\n"]

    # Checks
    ch = checks.run_checks()
    res["checks"] = [c.__dict__ for c in ch]
    md.append(f"\n## Verification checks: {sum(c.passed for c in ch)} of {len(ch)} pass\n\n")
    md.append(md_table([{**c.__dict__, "passed": "pass" if c.passed else "FAIL", "value": float(c.value)} for c in ch],
                       [("id", "Check", 0), ("name", "What", 0), ("value", "Model", 3), ("target", "Criterion", 0),
                        ("passed", "Result", 0)]))

    # Orbits
    legs = [{"leg": k, "dv": v.value, "kind": v.kind} for k, v in orbits.LEGS.items()]
    deps = [{"origin": o, "dv": orbits.mars_departure(o)} for o in ("LEO", "EML1", "NRHO", "LLO")]
    res["orbits"] = {"legs": legs, "mars_departure": deps}
    md.append("\n## Delta-v (shared table)\n\n")
    md.append(md_table(legs, [("leg", "Leg", 0), ("dv", "m/s", 0), ("kind", "Basis", 0)]))
    md.append("\nMars departure (minimum-energy v-infinity, 10% margin):\n\n")
    md.append(md_table(deps, [("origin", "From", 0), ("dv", "m/s", 0)]))

    # Sites
    ranked = [{"site": s.name, **sc} for s, sc in site.rank_sites()]
    res["sites"] = ranked
    md.append("\n## Site ranking\n\nWeights: " + ", ".join(f"{k} {v:.2f}" for k, v in site.WEIGHTS.items()) + "\n\n")
    md.append(md_table(ranked, [("site", "Site", 0), ("power", "Power", 2), ("night", "Night", 2), ("ice", "Ice", 2),
                                ("terrain", "Terrain", 2), ("comms", "Comms", 2), ("total", "Score", 3)]))
    best = site.rank_sites()[0][0]
    sun = site.illumination_series(best)
    spells = site.dark_spells_days(sun)

    # Power
    rows = []
    for load in (40.0, 100.0, 300.0):
        for p, m in power.size_architectures(sun, load):
            rows.append({"load": load, "arch": p.name, "solar": p.solar_kw, "fission": p.fission_kwe,
                         "storage": p.storage_kwh, "mass": m["total_t"]})
    trade = power.isru_power_trade(sun, 100.0, 2_000.0)
    res["power"] = {"architectures": rows, "isru_trade": trade, "dark_spells_days_max": float(spells.max())}
    md.append(f"\n## Power through the lunar night ({best.name})\n\n"
              f"Synthetic two-year series: lit {sun.mean():.1%}, longest dark spell {spells.max():.1f} days.\n\n")
    md.append(md_table(rows, [("load", "Critical kW", 0), ("arch", "Architecture", 0), ("solar", "Solar kW", 0),
                              ("fission", "Fission kWe", 0), ("storage", "Storage kWh", 0), ("mass", "Mass t", 1)]))
    md.append("\nPropellant plant power (2 MW ISRU plus 100 kW critical):\n\n")
    md.append(md_table(trade, [("option", "Option", 0), ("power_mass_t", "Power mass t", 0),
                               ("capacity_factor", "ISRU capacity factor", 3),
                               ("mass_per_effective_kw_kg", "kg per effective kW", 1)]))

    # ISRU
    plants = []
    for prod, target in (("water", 1000.0), ("hydrolox", 1000.0), ("methalox", 1000.0)):
        for ice in (0.01, 0.056, 0.30):
            plants.append(isru.plant_for_production(target, ice, prod).summary())
    kc = isru.kornuta_check()
    res["isru"] = {"plants": plants, "kornuta_check": kc, "lunar_carbon_coverage": isru.lunar_carbon_coverage(),
                   "mre_kw_per_1000t_o2": isru.regolith_oxygen_power_kw(1000.0)}
    md.append("\n## ISRU plant sizing (1,000 t per year of product)\n\n"
              "For methalox the 1,000 t is lunar oxygen; the methane column is imported from Earth.\n\n")
    md.append(md_table(plants, [("product", "Product", 0), ("ice_wt_pct", "Ice wt%", 1), ("water_t_yr", "Water t/yr", 0),
                                ("propellant_t_yr", "Propellant t/yr", 0), ("imported_ch4_t_yr", "Earth CH4 t/yr", 0),
                                ("thermal_kw", "Heat kW", 0), ("electric_kw", "Electric kW", 0),
                                ("regolith_kt_yr", "Regolith kt/yr", 1), ("plant_mass_t", "Plant t", 0)]))
    md.append(f"\nLunar ice carbon (CO2 and CH4 from LCROSS) covers {isru.lunar_carbon_coverage():.1%} of the methane "
              f"needed to pair with lunar oxygen. Molten regolith electrolysis needs "
              f"{isru.regolith_oxygen_power_kw(1000.0):,.0f} kW per 1,000 t/yr of oxygen (no ice needed).\n")

    # Plume and pads
    pads = buildup.pad_summary()
    rng = [{"v": v, **{f"a{a}": plume.ejecta_range_km(v, a) for a in (1, 3)}} for v in (100, 300, 1000, 1500, 2000)]
    res["plume"] = {"pads": pads, "ejecta_range_km": rng}
    md.append("\n## Landing and launch pads\n\n")
    md.append(md_table(pads, [("lander", "Case", 0), ("peak_kpa", "Peak kPa", 1), ("pad_radius_m", "Hard pad radius m", 0),
                              ("fines_radius_m", "Dust stripped to m", 0), ("disturbed_radius_m", "Disturbed to m", 0),
                              ("erosion_vs_apollo", "Erosion x Apollo", 0), ("sinter_days_200kw", "Sinter days at 200 kW", 0),
                              ("berm_m", "Berm m", 1), ("berm_t", "Berm t", 0)]))
    md.append("\nEjecta range (km) on the airless Moon:\n\n")
    md.append(md_table(rng, [("v", "Speed m/s", 0), ("a1", "1 deg", 1), ("a3", "3 deg", 1)]))

    # Construction
    cover = construction.cover_for_dose()
    hab = [{"hab": h.name, "cover": cover, "mass": construction.cover_mass_t(h, cover),
            "days": construction.excavation_days(construction.cover_mass_t(h, cover))} for h in construction.HABITATS]
    res["construction"] = {"surface_dose_msv_yr": construction.dose_msv_yr(0), "cover_m": cover, "habitats": hab}
    md.append(f"\n## Habitat shielding\n\nSurface GCR dose {construction.dose_msv_yr(0):.0f} mSv/yr (Chang'e 4). "
              f"{cover:.1f} m of regolith meets 50 mSv/yr with 95% time inside.\n\n")
    md.append(md_table(hab, [("hab", "Habitat", 0), ("mass", "Regolith t", 0), ("days", "Days, 2 excavators", 0)]))

    # Depots and shuttles
    dep = [depot.depot(p, m, loc).__dict__ for p, m in (("LOX", 1250.0), ("LCH4", 350.0), ("LH2", 150.0))
           for loc in ("surface_shaded", "orbit")]
    sh = [s.__dict__ for s in depot.shuttle_cases()]
    res["depot"] = {"depots": dep, "shuttles": sh}
    md.append("\n## Depots and shuttles\n\n")
    md.append(md_table(dep, [("prop", "Propellant", 0), ("mass_t", "t", 0), ("location", "Where", 0),
                             ("boiloff_pct_per_month", "Boil-off %/month", 2), ("zbo_power_kw", "Zero boil-off kW", 1)]))
    md.append("\n")
    md.append(md_table(sh, [("name", "Shuttle", 0), ("isp_s", "Isp s", 0), ("delivered_t", "Delivered t", 0),
                            ("gear_ratio", "Delivered / loaded", 2),
                            ("imported_fuel_per_t_lunar_ox_delivered", "Earth CH4 per t lunar O2", 2)]))

    # Mars and sorties
    ms = [s.__dict__ for s in mars_benefit.mars_scenarios()]
    ms150 = [s.__dict__ for s in mars_benefit.sensitivity_dry_mass()]
    so = [s.__dict__ for s in mars_benefit.lunar_sorties()]
    res["mars"] = {"scenarios": ms, "scenarios_150t_dry": ms150, "sorties": so,
                   "launches_per_t_to_lunar_surface": mars_benefit.lunar_cargo_launches_per_t(mars_benefit.context())}
    md.append("\n## Does lunar propellant reduce Earth launches?\n\nMars cargo mission, 100 t landed:\n\n")
    md.append(md_table(ms, [("name", "Scenario", 0), ("earth_launches", "Earth launches", 1),
                            ("lunar_water_t", "Lunar water t", 0), ("notes", "Notes", 0)]))
    md.append("\nSame with a 150 t ship dry mass (matches SpaceX's stated 100 t to LEO):\n\n")
    md.append(md_table(ms150, [("name", "Scenario", 0), ("earth_launches", "Earth launches", 1),
                               ("lunar_water_t", "Lunar water t", 0)]))
    md.append("\nLunar sortie (Starship-class lander, 20 t payload, LEO to NRHO to surface to NRHO):\n\n")
    md.append(md_table(so, [("name", "Case", 0), ("earth_launches", "Earth launches", 1), ("lunar_o2_t", "Lunar O2 t", 0),
                            ("notes", "Notes", 0)]))

    # Buildup
    bu = [{"phase": r.phase.name, "years": r.phase.years, "crew": r.phase.crew, "critical_kw": r.phase.critical_kw,
           "isru_kw": r.isru_kw, "water": r.water_t_yr, "power": r.power_arch, "power_t": r.power_mass_t,
           "landed": r.landed_t, "landings": r.cargo_landings, "launches": r.earth_launches} for r in buildup.evaluate()]
    res["buildup"] = bu
    md.append("\n## Phased buildup\n\n")
    md.append(md_table(bu, [("phase", "Phase", 0), ("years", "When", 0), ("crew", "Crew", 0),
                            ("critical_kw", "Critical kW", 0), ("isru_kw", "ISRU kW", 0), ("water", "Water t/yr", 0),
                            ("power", "Power", 0), ("landed", "New landed t", 0), ("landings", "Cargo landings", 0),
                            ("launches", "Earth launches", 0)]))
    md.append(f"\nTotal: {sum(r['landed'] for r in bu):,.0f} t landed, {sum(r['launches'] for r in bu):,.0f} Earth launches "
              "for cargo (crew flights not included).\n")

    # Reuse map
    res["reuse"] = reuse.table()
    md.append("\n## Capability reuse\n\n")
    md.append(md_table(reuse.table(), [("capability", "Capability", 0), ("source", "Source", 0), ("lunar use", "Use", 0),
                                       ("status", "Status", 0)]))

    # Provenance
    specs = {}
    for mod in (orbits, site, power, isru, plume, construction, depot, mars_benefit):
        if hasattr(mod, "SPEC"):
            specs.update({f"{mod.__name__.split('.')[-1]}.{k}": v for k, v in mod.SPEC.items()})
    specs.update({f"orbits.{k}": v for k, v in orbits.LEGS.items()})
    for s in site.SITES:
        for fld in ("illumination", "longest_dark_days", "psr_distance_km", "slope_deg", "earth_visibility"):
            specs[f"site.{s.name}.{fld}"] = getattr(s, fld)
    prov = provenance.table(specs)
    with open(OUT / "provenance.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(prov[0]))
        w.writeheader()
        w.writerows(prov)
    counts = {k: sum(1 for r in prov if r["kind"] == k) for k in provenance.KINDS}
    res["provenance_counts"] = counts
    md.append(f"\n## Provenance\n\n{len(prov)} inputs: " + ", ".join(f"{v} {k}" for k, v in counts.items()) + ".\n")

    (OUT / "summary.md").write_text("".join(md))
    (OUT / "results.json").write_text(json.dumps(jsonable(res), indent=1))
    if plots:
        make_plots(sun, best)
    return res


def make_plots(sun: np.ndarray, best: site.Site) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    # Illumination and storage state of charge, outpost on solar + RFC
    arch = [a for a in power.size_architectures(sun, 40.0) if a[0].storage == "rfc"][0][0]
    soc, s, eta = [], arch.storage_kwh, power._eff("rfc")
    for x in sun:
        net = arch.solar_kw * x - 40.0
        s = min(arch.storage_kwh, s + net * eta) if net > 0 else s + net / eta
        soc.append(s / arch.storage_kwh)
    t = np.arange(len(sun)) / 24
    fig, ax = plt.subplots(2, 1, figsize=(9, 5), sharex=True)
    ax[0].plot(t, sun, lw=0.6, color="#c98a00")
    ax[0].set_ylabel("Sun disk visible")
    ax[0].set_title(f"{best.name}: synthetic illumination and outpost storage (40 kW)")
    ax[1].plot(t, soc, lw=0.8, color="#2b6cb0")
    ax[1].set_ylabel("RFC state of charge")
    ax[1].set_xlabel("day")
    fig.tight_layout()
    fig.savefig(OUT / "power_night.png", dpi=130)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 4.5))
    for l in plume.landers()[1:]:
        r, p, tau = plume.radial_profile(plume.lander_nozzles(l), r_max=2000)
        ax.loglog(r, tau, label=l.name, lw=1)
    for k in ("tau_fines", "tau_gravel"):
        ax.axhline(plume.SPEC[k].value, ls="--", color="grey", lw=0.8)
    ax.set_xlabel("distance from vehicle axis, m")
    ax.set_ylabel("surface shear, Pa")
    ax.set_ylim(1e-3, 1e5)
    ax.legend(fontsize=7)
    ax.set_title("Plume wall shear on the surface (dashed: dust and gravel thresholds)")
    fig.tight_layout()
    fig.savefig(OUT / "plume_shear.png", dpi=130)
    plt.close(fig)

    ms = mars_benefit.mars_scenarios()
    fig, ax = plt.subplots(figsize=(8, 3.2))
    ax.barh([m.name for m in ms][::-1], [m.earth_launches for m in ms][::-1], color=["#2f855a", "#c53030", "#718096"])
    ax.set_xlabel("Earth launches per Mars cargo mission (100 t landed)")
    fig.tight_layout()
    fig.savefig(OUT / "mars_launches.png", dpi=130)
    plt.close(fig)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--plots", action="store_true")
    a = ap.parse_args()
    r = main(a.plots)
    print((OUT / "summary.md").read_text())
