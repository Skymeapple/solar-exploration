"""Run the settlement study and write results/settlement/.

    python scripts/run_settlement_study.py [--quick]

--quick uses fewer Monte Carlo runs (for CI); the committed results use the default.
"""
from __future__ import annotations

import argparse
import csv
import json
import math
from pathlib import Path

from raptor_sim.settlement import capabilities, energy, growth, health, inputs, life_support, population, radiation

OUT = Path(__file__).resolve().parent.parent / "results" / "settlement"


def write_csv(name: str, rows: list[dict]) -> None:
    with open(OUT / name, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        for r in rows:
            w.writerow({k: (round(x, 6) if isinstance(x, float) else x) for k, x in r.items()})


def fmt(x, nd=0):
    if x is None:
        return "not reached"
    if isinstance(x, float) and math.isinf(x):
        return "never"
    return f"{x:,.{nd}f}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    args = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    reps = 4 if args.quick else 20
    sizes = (20, 50, 160, 500) if args.quick else (20, 50, 100, 160, 500, 2000)
    L = ["# Settlement study summary", "", "Generated by `scripts/run_settlement_study.py`. Inputs and their basis (cited, model, estimate, unknown) are in `inputs.csv`.", ""]

    # Inputs register
    with open(OUT / "inputs.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["name", "value", "unit", "basis", "source", "note"])
        w.writerows(inputs.table_rows())
    counts = {}
    for p in inputs.PARAMS.values():
        counts[p.basis] = counts.get(p.basis, 0) + 1
    L += ["Input basis count: " + ", ".join(f"{k} {n}" for k, n in sorted(counts.items())), ""]

    # Verification
    sim, ana = population.wright_fisher_check()
    checks = [("V1 genetics vs Wright-Fisher theory", abs(sim - ana) / ana < 0.03, f"H_t/H_0 simulated {sim:.4f} vs analytic {ana:.4f}")]
    bal = all(r["balances_close"] for r in life_support.stage_table())
    checks.append(("V2 life-support mass balance closes", bal, "demand = recycled + local + imported for O2, water, food at every stage"))
    p = energy.propellant_energy()
    checks.append(("V3 propellant stoichiometry", abs(p.o2_surplus_kg_per_kg - (4 - 3.6) / 4.6) < 1e-9, f"{p.kwh_per_kg_propellant:.2f} kWh/kg, water {p.water_kg_per_kg:.3f} kg/kg, O2 surplus {p.o2_surplus_kg_per_kg:.3f} kg/kg"))
    rad0 = radiation.annual_dose_msv(radiation.Exposure("Mars", 0.0, 0.0)) / 365.25
    checks.append(("V4 unshielded Mars dose equals RAD", abs(rad0 - 0.64) < 1e-9, f"{rad0:.3f} mSv/day vs 0.64 measured"))
    syn = growth.synodic_period_days()
    checks.append(("V5 synodic period from orbits", abs(syn - 779.9) < 1.0, f"{syn:.1f} days vs 779.9 published"))
    lo, hi = health.comms_delay_minutes()
    checks.append(("V6 light-time range", 3.0 < lo < 4.5 and 20.0 < hi < 22.5, f"{lo:.1f}-{hi:.1f} min one way (published 3-22 min; circular orbits)"))
    L += ["## Verification checks", "", "| Check | Result | Detail |", "| --- | --- | --- |"]
    L += [f"| {n} | {'PASS' if ok else 'FAIL'} | {d} |" for n, ok, d in checks]
    L.append("")

    # Population
    rows = []
    for label, kw in (("closed colony", {}), ("closed, 1%/yr catastrophe risk", {"catastrophe_rate": 0.01}), ("closed, plus frozen gamete bank for 10% of births", {"bank_share": 0.1})):
        for r in population.viability_study(founder_sizes=sizes, reps=reps, **kw):
            rows.append({"scenario": label, **r})
    write_csv("population_viability.csv", rows)
    L += ["## Population and genetics (300 years, habitat capacity 3x founders, random mating)", "",
          "| Scenario | Founders | Extinction risk | Heterozygosity kept | Inbreeding F | Founder-private variants kept | Ne |", "| --- | --- | --- | --- | --- | --- | --- |"]
    L += [f"| {r['scenario']} | {r['founders']} | {r['extinction_probability']:.0%} | {r['heterozygosity_kept']:.3f} | {r['inbreeding_F']:.3f} | {r['founder_alleles_kept']:.0%} | {fmt(r['ne_estimate']) if r['ne_estimate'] < 1e5 else 'rising'} |" for r in rows]
    L += ["", f"Literature: Smith 2014 gives 14,000-44,000 founders with no later gene flow; Moore 2003 gives 150-180 with managed mating; the 50/500 rule asks for Ne 50 short term and 500 long term.", ""]

    # Life support
    ls = life_support.stage_table()
    write_csv("life_support.csv", ls)
    L += ["## Closed-loop life support (per resident per year)", "", "| Stage | Water recovery | O2 recovery | Food grown | Demand (kg) | Imported (kg) | Closure |", "| --- | --- | --- | --- | --- | --- | --- |"]
    L += [f"| {r['stage']} | {r['water_recovery']:.0%} | {r['o2_recovery']:.0%} | {r['food_local']:.0%} | {r['demand_kg']:,.0f} | {r['import_kg']:,.0f} | {r['closure']:.1%} |" for r in ls]
    L.append("")

    # Energy
    d = energy.demand_per_person()
    d_sun = energy.demand_per_person(sunlit_share=0.4)
    sup = energy.supply_table()
    write_csv("energy_supply.csv", sup)
    plant_kw = energy.propellant_plant_kw(inputs.v("return_propellant_isru"), syn)
    L += ["## Energy", "", "| Demand per resident | kW |", "| --- | --- |"]
    L += [f"| {k.replace('_kw', '').replace('_', ' ')} | {x:.1f} |" for k, x in d.items()]
    L += ["", f"With 40% of crop light from sunlit greenhouses, total falls to {d_sun['total_kw']:.1f} kW. Industry ({inputs.v('industry_power_per_person'):.0f} kW) is tagged unknown.", "",
          f"Propellant plant: {p.kwh_per_kg_propellant:.2f} kWh per kg of CH4/LOX; refuelling one ship ({inputs.v('return_propellant_isru'):.0f} t) per window takes {plant_kw:.0f} kW continuous.", "",
          "| Site | Solar + batteries (kg/kWe) | Solar, storm-proof (kg/kWe) | Fission (kg/kWe) |", "| --- | --- | --- | --- |"]
    L += [f"| {r['site']} | {r['solar_kg_per_kwe']:,.0f} | {r['solar_storm_proof_kg_per_kwe']:,.0f} | {r['fission_kg_per_kwe']:,.0f} |" for r in sup]
    L.append("")

    # Radiation
    rt = radiation.dose_table()
    write_csv("radiation.csv", rt)
    L += ["## Radiation", "", "| Case | Annual (mSv) | Total (mSv) | Total range, lambda 100-250 (mSv) | Excess cancer risk (band) |", "| --- | --- | --- | --- | --- |"]
    L += [f"| {r['case']} | {r['annual_msv']:.0f} | {r['total_msv']:,.0f} | {r['total_msv_lam100']:,.0f}-{r['total_msv_lam250']:,.0f} | {r['risk']:.1%} ({r['risk_low']:.1%}-{r['risk_high']:.0%}) |" for r in rt]
    L += ["", "Shield needed for an annual dose target, 4 h/week outside in a suit:", "", "| Target (mSv/yr) | Mars (g/cm2, m regolith) | Moon (g/cm2, m regolith) |", "| --- | --- | --- |"]
    for t in (50.0, 20.0, 10.0, 6.0):
        a, b = radiation.shield_needed("Mars", t), radiation.shield_needed("Moon", t)
        L.append(f"| {t:.0f} | {fmt(a)} ({fmt(radiation.regolith_depth_m(a), 1)}) | {fmt(b)} ({fmt(radiation.regolith_depth_m(b), 1)}) |")
    a0 = radiation.shield_needed("Mars", 2.4, hours_outside=0.0)
    L += ["", f"Outdoor time sets a floor: 4 h/week in a suit alone gives ~{radiation.annual_dose_msv(radiation.Exposure('Mars', 1e4, 4.0)):.1f} mSv/yr on Mars. With no outdoor time, Earth-background dose (2.4 mSv/yr) needs {fmt(a0)} g/cm2 ({fmt(radiation.regolith_depth_m(a0), 1)} m).", ""]

    # Health
    bt = health.bone_table()
    write_csv("bone_hypotheses.csv", bt)
    L += ["## Partial-gravity bone loss (three hypotheses, with exercise; the science is unknown)", "", "| Site | Hypothesis | Bone after 2.5 yr | After 10 yr | Set point | Years to osteoporosis-level loss |", "| --- | --- | --- | --- | --- | --- |"]
    L += [f"| {r['site']} | {r['hypothesis']} | {r['bone_after_2_5_yr']:.0%} | {r['bone_after_10_yr']:.0%} | {r['set_point']:.0%} | {fmt(r['years_to_osteoporosis'], 1)} |" for r in bt]
    mc = [health.medical_capacity(n) for n in (100, 1_000, 10_000, 100_000, 1_000_000)]
    write_csv("medical_capacity.csv", mc)
    L += ["", "| Population | Physicians | Surgical emergencies/yr | P(emergency between ships) | Births/yr |", "| --- | --- | --- | --- | --- |"]
    L += [f"| {r['population']:,} | {r['physicians_needed']:.1f} | {r['surgical_emergencies_per_year']:.1f} | {r['p_surgical_emergency_between_ships']:.0%} | {r['births_per_year_at_tfr']:,.0f} |" for r in mc]
    L += ["", f"One-way light time Earth-Mars: {lo:.1f} to {hi:.1f} minutes, plus about two weeks of blackout at solar conjunction every {syn:.0f} days.", ""]

    # Growth
    allsteps, ms = [], []
    for s in growth.scenarios():
        st = growth.run(s)
        for x in st:
            allsteps.append({"scenario": s.name, **x.__dict__})
        ms.append({"scenario": s.name, **growth.milestones(st)})
    write_csv("growth_trajectories.csv", allsteps)
    write_csv("growth_milestones.csv", ms)
    L += [f"## Growth versus resupply ({growth.GrowthScenario().windows} windows of {syn:.0f} days, 100 t per ship)", "",
          "| Scenario | 1k people | 10k | 100k | 1M | 90% local | 98% local | Population at end | Peak power (MW) |", "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for m in ms:
        L.append(f"| {m['scenario']} | {fmt(m['year_pop_1000'])} | {fmt(m['year_pop_10000'])} | {fmt(m['year_pop_100000'])} | {fmt(m['year_pop_1000000'])} | {fmt(m['year_f_local_90'])} | {fmt(m['year_f_local_98'])} | {m['final_population']:,.0f} | {m['peak_power_mw']:,.0f} |")
    L += ["", "Years are from the first landing. 'Local' is the share of residents' needs made on Mars; how it rises with population (N_half) is unknown and drives every row.", ""]

    # Capabilities
    m = capabilities.matrix()
    sites = list(capabilities.SITES)
    with open(OUT / "capability_matrix.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["capability", *sites])
        for c, row in m.items():
            w.writerow([c, *[row[s] for s in sites]])
    sc = capabilities.reuse_scores()
    L += ["## Capability reuse across sites", "", "| Capability | " + " | ".join(sites) + " |", "| --- |" + " --- |" * len(sites)]
    L += [f"| {c} | " + " | ".join(row[s] for s in sites) + " |" for c, row in m.items()]
    L += ["| **Reuse score** | " + " | ".join(f"{sc[s]:.0%}" for s in sites) + " |", ""]

    (OUT / "summary.md").write_text("\n".join(L) + "\n")
    json.dump({"checks": [{"name": n, "passed": ok, "detail": d} for n, ok, d in checks], "growth_milestones": ms, "reuse_scores": sc}, open(OUT / "summary.json", "w"), indent=2, default=str)
    print("\n".join(L))
    if not all(ok for _, ok, _ in checks):
        raise SystemExit("verification check failed")


if __name__ == "__main__":
    main()
