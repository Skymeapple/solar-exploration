"""Crewed mission research study: runs every crew model and writes
results/crew/summary.md and results/crew/data.json."""

from __future__ import annotations

import json
import math
from dataclasses import asdict
from pathlib import Path

from raptor_sim.crew import aborts as AB
from raptor_sim.crew import entry as E
from raptor_sim.crew import gravity as GR
from raptor_sim.crew import life_support as LS
from raptor_sim.crew import missions as MS
from raptor_sim.crew import propulsion as PR
from raptor_sim.crew import radiation as RAD
from raptor_sim.crew.transfers import conjunction_class, trip_time_trade
from raptor_sim.crew.verification import run_all

OUT = Path(__file__).resolve().parents[1] / "results" / "crew"


def fmt(x, nd=0):
    if isinstance(x, float) and (math.isinf(x) or math.isnan(x)):
        return "n/a"
    return f"{x:,.{nd}f}"


def table(headers, rows):
    s = "| " + " | ".join(headers) + " |\n| " + " | ".join("---" for _ in headers) + " |\n"
    for r in rows:
        s += "| " + " | ".join(str(c) for c in r) + " |\n"
    return s


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    data = {}
    md = ["# Crewed mission research: simulation results\n",
          "Generated by `scripts/run_crew_study.py`. Every input is tagged CITED or ESTIMATE in the module "
          "docstrings under `src/raptor_sim/crew/`.\n"]

    # Verification
    checks = run_all()
    data["verification"] = [asdict(c) for c in checks]
    md.append("## Verification (CV1 to CV8)\n")
    md.append(table(["ID", "Check", "Model", "Reference", "Error", "Band", "Basis", "Result"],
                    [[c.id, c.name, f"{c.value:.4g}", f"{c.reference:.4g}", f"{c.error:.2e}", c.band, c.basis,
                      "PASS" if c.passed else "FAIL"] for c in checks]))

    # Trip time
    trade = trip_time_trade(tofs=range(80, 281, 20))
    rate20 = RAD.gcr_rate(20.0, "aluminum", "min")
    data["trip_time"] = [dict(tof=p.tof_days, depart=p.leg.depart, tmi=p.tmi_dv, c3=p.leg.c3,
                              mars_entry=p.arrival_entry_speed, capture_dv=p.arrival_capture_dv,
                              dose_one_way=p.tof_days * rate20) for p in trade]
    md.append("\n## Earth to Mars trip time trade (2028-29 window)\n")
    md.append("Cheapest departure for each flight time. TMI from a 300 km orbit; arrival by aerocapture "
              "(entry speed) or propulsive capture into a 1-sol orbit. Dose: one leg behind 20 g/cm2 aluminium "
              "at solar minimum.\n\n")
    md.append(table(["Flight time (d)", "Depart", "TMI (m/s)", "C3 (km2/s2)", "Mars entry (m/s)", "Capture dv (m/s)",
                     "One-leg dose (mSv)"],
                    [[p["tof"], p["depart"], fmt(p["tmi"]), fmt(p["c3"], 1), fmt(p["mars_entry"]), fmt(p["capture_dv"]),
                      fmt(p["dose_one_way"])] for p in data["trip_time"]]))

    # Radiation
    rows = []
    for mat in ("aluminum", "water", "polyethylene"):
        rows.append([mat] + [fmt(RAD.gcr_rate(x, mat, "min"), 2) for x in (0, 10, 20, 40, 80)])
    data["radiation"] = dict(
        calibration=asdict(RAD.CAL), moon_prediction=RAD.CAL.predict_moon(),
        rates={mat: {x: RAD.gcr_rate(x, mat, "min") for x in (0, 5, 10, 20, 30, 40, 60, 80)}
               for mat in ("aluminum", "water", "polyethylene")},
        rates_solar_max={mat: {x: RAD.gcr_rate(x, mat, "max") for x in (0, 5, 10, 20, 30, 40, 60, 80)}
                         for mat in ("aluminum", "water", "polyethylene")},
        mars_surface_10=RAD.gcr_rate(10, "regolith", "min", "mars_surface"),
        moon_surface_10=RAD.gcr_rate(10, "regolith", "min", "moon_surface"),
        shelter_1in100=RAD.shelter_needed(10.0, 1.0), shelter_3x=RAD.shelter_needed(10.0, 3.0),
        max_transit_days={f"{m}_{x}": RAD.max_transit_days_within_limit(x, m) for m in ("aluminum", "polyethylene")
                          for x in (10, 20, 40)},
        max_transit_days_with_500d_surface={f"{m}_{x}": RAD.max_transit_days_within_limit(x, m, surface_days=500)
                                            for m in ("aluminum", "polyethylene") for x in (10, 20, 40)},
        sensitivity=RAD.calibration_sensitivity(),
    )
    md.append("\n## Radiation\n")
    md.append(f"Calibration: aluminium plateau {RAD.CAL.plateau_al:.2f}, unshielded deep-space rate at the RAD epoch "
              f"{RAD.CAL.free_space_msv_d:.2f} mSv/day. Chang'e-4 check: {RAD.CAL.predict_moon():.2f} vs 1.37 mSv/day.\n\n")
    md.append("GCR dose-equivalent rate in deep space at solar minimum (mSv/day) vs shield depth (g/cm2):\n\n")
    md.append(table(["Material", "0", "10", "20", "40", "80"], rows))
    md.append(f"\nMars surface under 10 g/cm2 regolith: {fmt(data['radiation']['mars_surface_10'], 2)} mSv/day; "
              f"Moon: {fmt(data['radiation']['moon_surface_10'], 2)} mSv/day (solar minimum).\n\n")
    md.append(f"SPE storm shelter (on top of a 10 g/cm2 hull) to stay under the 250 mGy-Eq 30-day BFO limit: "
              f"{fmt(data['radiation']['shelter_1in100'], 1)} g/cm2 for an August-1972-class event, "
              f"{fmt(data['radiation']['shelter_3x'], 1)} g/cm2 for an event three times larger. NASA's guidance "
              f"is 10 to 20 cm water.\n\n")
    md.append("Longest transit (days) that stays under 600 mSv, solar minimum:\n\n")
    md.append(table(["Hull", "No surface stay", "With 500-day Mars stay"],
                    [[k.replace("_", " ") + " g/cm2", fmt(v), fmt(data["radiation"]["max_transit_days_with_500d_surface"][k])]
                     for k, v in data["radiation"]["max_transit_days"].items()]))
    md.append("\nCalibration sensitivity (other plausible RAD depth and attenuation length):\n\n")
    md.append(table(["RAD depth", "lambda", "Al plateau", "Moon prediction", "Deep space @20 g/cm2"],
                    [[r["rad_depth"], r["lam"], fmt(r["plateau_al"], 2), fmt(r["moon_pred"], 2),
                      fmt(r["deep_space_20gcm2_solar_min"], 2)] for r in data["radiation"]["sensitivity"]]))

    # Life support
    bal = LS.crew_day_balance()
    cons = {l: asdict(LS.consumables(6, 950, l)) for l in LS.LOOPS}
    data["life_support"] = dict(balance=dict(inputs=bal.inputs, outputs=bal.outputs, imbalance=bal.imbalance),
                                consumables_6crew_950d=cons,
                                break_even={l: LS.break_even_days(6, l) for l in ("iss", "advanced", "bioregenerative")},
                                curve={l: [[d, LS.consumables(6, d, l).total_kg / 1e3] for d in range(0, 2001, 100)]
                                       for l in LS.LOOPS})
    md.append("\n## Life support\n")
    md.append("Per crew-member-day balance (kg): inputs " +
              ", ".join(f"{k} {v:.2f}" for k, v in bal.inputs.items()) + "; outputs " +
              ", ".join(f"{k} {v:.2f}" for k, v in bal.outputs.items()) + f". Residual {bal.imbalance:.1e} kg.\n\n")
    md.append("Six crew, 950 days (conjunction-class Mars mission), launch mass in kg:\n\n")
    md.append(table(["Loop", "O2", "Water", "Food", "Spares", "Hardware", "Reserve", "Total"],
                    [[LS.LOOPS[l].name, fmt(c["o2_kg"]), fmt(c["water_kg"]), fmt(c["food_kg"]), fmt(c["spares_kg"]),
                      fmt(c["hardware_kg"]), fmt(c["reserve_kg"]), fmt(c["total_kg"])] for l, c in cons.items()]))
    md.append("\nBreak-even mission length against open loop (6 crew): " +
              ", ".join(f"{l} {fmt(d)} days" for l, d in data["life_support"]["break_even"].items()) + ".\n")

    # Entry
    erows, edata = [], []
    cases = [(E.CAPSULE_ORION_CLASS, "earth", v) for v in (11_000, 12_500, 14_000)] + \
            [(E.SHIP_STARSHIP_CLASS, "earth", v) for v in (11_000, 12_500)] + \
            [(E.SHIP_STARSHIP_CLASS_MARS, "mars", v) for v in (6_000, 7_500, 9_000)]
    for veh, pl, v in cases:
        c = E.entry_corridor(veh, pl, v, MS.G_LIMIT_DECONDITIONED)
        mid = 0.5 * (c.shallow_deg + c.steep_deg)
        r = E.simulate_entry(veh, pl, v, mid, bank=0.0) if c.width_deg > 0 else None
        d = dict(vehicle=veh.name, planet=pl, v=v, beta=veh.ballistic_coeff, shallow=c.shallow_deg, steep=c.steep_deg,
                 width=c.width_deg, mid_peak_g=r.peak_g if r else float("nan"),
                 mid_peak_heat_W_cm2=r.peak_heat_flux / 1e4 if r else float("nan"),
                 mid_radiative_W_cm2=r.peak_radiative / 1e4 if r else float("nan"),
                 profile=[[float(t), float(h), float(vv), float(g)] for t, h, vv, g in
                          zip(r.t[::20], r.h[::20], r.v[::20], r.g[::20])] if r else [])
        edata.append(d)
        erows.append([veh.name, pl, fmt(v), fmt(veh.ballistic_coeff), fmt(c.shallow_deg, 2), fmt(c.steep_deg, 2),
                      fmt(c.width_deg, 2), fmt(d["mid_peak_g"], 1), fmt(d["mid_peak_heat_W_cm2"]),
                      fmt(d["mid_radiative_W_cm2"])])
    data["entry"] = edata
    md.append("\n## Entry corridors (5 g limit for deconditioned crew)\n")
    md.append("Overshoot = shallowest angle captured with full lift down; undershoot = steepest angle under 5 g "
              "with full lift up. Peak g and stagnation heating for an entry at mid-corridor, lift up.\n\n")
    md.append(table(["Vehicle", "Planet", "Entry speed (m/s)", "Ballistic coeff (kg/m2)", "Overshoot (deg)",
                     "Undershoot (deg)", "Width (deg)", "Peak g", "Peak heat (W/cm2)", "of which radiative"], erows))

    # Aborts
    rt = conjunction_class()
    ab400 = AB.trans_mars_abort(rt.outbound, dv_budget=2_000, max_return_days=400)
    ab800 = AB.trans_mars_abort(rt.outbound, dv_budget=2_000, max_return_days=800)
    wait = AB.mars_surface_wait(rt.outbound.depart_jd + rt.outbound.tof_days, int(rt.stay_days), rt.tei_dv * 1.1)
    data["aborts"] = dict(
        outbound=dict(depart=rt.outbound.depart, tof=rt.outbound.tof_days),
        trans_mars_400=[asdict(p) for p in ab400], trans_mars_800=[asdict(p) for p in ab800],
        coverage_400=AB.coverage(ab400), coverage_800=AB.coverage(ab800), surface_wait=wait)
    md.append("\n## Abort coverage (conjunction-class outbound leg, 2 km/s abort budget)\n")
    md.append(table(["Day after TMI", "Cheapest return dv, <=400 d (m/s)", "Return time (d)",
                     "Cheapest return dv, <=800 d (m/s)", "Return time (d)"],
                    [[a.day, fmt(a.best_dv), fmt(a.return_days), fmt(b.best_dv), fmt(b.return_days)]
                     for a, b in zip(ab400[::2], ab800[::2])]))
    md.append(f"\nCoverage with a 2 km/s budget: {AB.coverage(ab400):.0%} (return within 400 days), "
              f"{AB.coverage(ab800):.0%} (within 800 days). From the Mars surface, the wait for a return window "
              f"is {fmt(wait[0][1])} days on arrival day and falls to zero at the planned departure.\n")

    # Gravity
    data["gravity"] = dict(
        spin=[asdict(GR.spin_design(g, rpm)) for g in (0.38, 0.5, 1.0) for rpm in (1, 2, 4, 6)],
        tether=asdict(GR.tethered_pair()),
        bone={f"{d}d": dict(none=GR.bone_loss_fraction(d, False), exercise=GR.bone_loss_fraction(d, True),
                            mars_g=GR.bone_loss_fraction(d, True, 0.38)) for d in (30, 180, 360, 500, 1000)})
    md.append("\n## Artificial gravity and deconditioning\n")
    md.append(table(["g level", "rpm", "Radius (m)", "Rim speed (m/s)", "Head-foot gradient", "Coriolis/g (1 m/s walk)",
                     "In comfort envelope"],
                    [[s["g_level"], s["rpm"], fmt(s["radius_m"]), fmt(s["rim_speed"], 1), f"{s['gradient_head_foot']:.1%}",
                      fmt(s["coriolis_ratio"], 2), "yes" if s["meets_envelope"] else "no"] for s in data["gravity"]["spin"]]))
    t = data["gravity"]["tether"]
    md.append(f"\nTethered pair (150 t crew ship + 150 t counterweight, 0.38 g at 4 rpm): tether {fmt(t['tether_length_m'])} m, "
              f"{fmt(t['tether_mass_kg'])} kg, rim speed {fmt(t['spin_up_dv'], 1)} m/s.\n\n")
    md.append(table(["Days in 0 g", "Bone loss, no exercise", "With exercise", "With exercise at 0.38 g"],
                    [[k, f"{v['none']:.1%}", f"{v['exercise']:.1%}", f"{v['mars_g']:.1%}"] for k, v in data["gravity"]["bone"].items()]))

    # Propulsion
    cap120 = MS.starship_crew_capability(120.0)
    cap150 = MS.starship_crew_capability(150.0)
    nep = []
    for p_mw, alpha in ((2, 20), (5, 10), (10, 5), (20, 5), (10, 20)):
        tr = PR.nep_trip(PR.NEPSystem("", p_mw, alpha, 4000.0, 0.6), 60.0 + LS.consumables(6, 600, "iss").total_kg / 1e3)
        nep.append(dict(power=p_mw, alpha=alpha, m0=tr.initial_mass_t, days=tr.trip_days, thrust=tr.system.thrust()))
    impulsive = []
    for dv in (4000, 6000, 8000, 10000, 12000):
        impulsive.append(dict(dv=dv, chem=PR.stage_mass(PR.CHEM_CH4, 100.0, dv)[1], ntp=PR.stage_mass(PR.NTP_LH2, 100.0, dv)[1]))
    data["propulsion"] = dict(starship_120=asdict(cap120), starship_150=asdict(cap150), nep=nep, impulsive=impulsive)
    md.append("\n## Propulsion trades\n")
    for cap in (cap120, cap150):
        md.append(f"- Starship-class crew ship, dry {cap.ship_dry_t:.0f} t, crew payload {cap.payload_t:.0f} t: "
                  f"TMI capability {fmt(cap.tmi_capability)} m/s after full LEO refilling. Fastest transit "
                  f"{cap.fastest_tof_days} days if Mars entry is capped at 7.5 km/s; {cap.fastest_tof_no_entry_limit} days "
                  f"if any entry speed were survivable.\n")
    md.append("\nSingle stage, 100 t payload, initial mass in t:\n\n")
    md.append(table(["Delta-v (m/s)", "CH4/LOX 380 s", "NTP 900 s"],
                    [[fmt(r["dv"]), fmt(r["chem"]), fmt(r["ntp"])] for r in impulsive]))
    md.append("\nNEP Earth to Mars, heliocentric leg (L0):\n\n")
    md.append(table(["Power (MWe)", "Specific mass (kg/kWe)", "Thrust (N)", "Initial mass (t)", "Trip (days)"],
                    [[r["power"], r["alpha"], fmt(r["thrust"]), fmt(r["m0"]), fmt(r["days"])] for r in nep]))

    # Missions
    cases = MS.all_cases()
    data["missions"] = {k: m.row() for k, m in cases.items()}
    md.append("\n## Mission cases\n")
    md.append(table(["Mission", "Propulsion", "Out/stay/back (d)", "Total (d)", "Dose min-max solar (mSv)",
                     "Under 600 mSv", "Consumables (t)", "Earth entry (m/s)", "Entry peak g", "Bone loss"],
                    [[m.name, m.propulsion, f"{m.outbound_days:.0f}/{m.stay_days:.0f}/{m.return_days:.0f}",
                      fmt(m.total_days), f"{m.dose_solar_max:.0f}-{m.dose_solar_min:.0f}", "yes" if m.dose_ok else "NO",
                      fmt(m.consumables_t, 1), fmt(m.entry_speed_return), fmt(m.entry_peak_g, 1), f"{m.bone_loss:.1%}"]
                     for m in cases.values()]))
    md.append("\nNotes:\n\n" + "".join(f"- **{m.name}**: " + "; ".join(m.notes) + "\n" for m in cases.values()))

    (OUT / "summary.md").write_text("".join(md))
    (OUT / "data.json").write_text(json.dumps(data, indent=1, default=lambda o: None if o != o else str(o)))
    print(f"wrote {OUT/'summary.md'}")


if __name__ == "__main__":
    main()
