"""Crewed lunar mission study: landing simulations, architectures, sensitivities.

    python scripts/run_lunar_study.py

Writes results/crewed_lunar/summary.md and results/crewed_lunar/study.json.
"""

from __future__ import annotations

import json
import math
from dataclasses import asdict, replace
from pathlib import Path

from raptor_sim.crewed_lunar import architecture as arch
from raptor_sim.crewed_lunar import legs
from raptor_sim.crewed_lunar.earth_return import earth_return_checks
from raptor_sim.crewed_lunar.landing import Lander, simulate_ascent, simulate_descent
from raptor_sim.crewed_lunar.reference import APOLLO_LM, EARTH_RETURN, RAPTOR, STARSHIP_HLS, TRAJECTORY
from raptor_sim.engine import size_engine
from raptor_sim.mission import Vehicle, vehicle_performance

OUT = Path(__file__).resolve().parent.parent / "results" / "crewed_lunar"


def thin(traj: dict, n: int = 150) -> dict:
    k = max(len(traj["t"]) // n, 1)
    return {key: [round(x, 3) for x in val[::k]] + [round(val[-1], 3)] for key, val in traj.items()}


def apollo_validation():
    L = APOLLO_LM
    lm = Lander("Apollo LM", L["total_wet"].value, L["dps_thrust"].value, L["dps_isp"].value,
                L["dps_throttle_min"].value)
    d = simulate_descent(lm)
    asc_lander = Lander("Apollo LM ascent stage", L["ascent_wet"].value, L["aps_thrust"].value,
                        L["aps_isp"].value, 1.0)
    a = simulate_ascent(asc_lander)
    return d, a


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    study: dict = {}
    md = ["# Crewed lunar mission study", "",
          "Generated by `scripts/run_lunar_study.py`. Status tags: cited (source in "
          "`crewed_lunar/reference.py`), computed (this model), estimated (our assumption).", ""]

    # 1. Patched-conic legs
    md += ["## 1. Cislunar legs (computed)", "", "| Leg | Model | Cited check |", "| --- | --- | --- |",
           f"| LEO 300 km to trans-lunar injection | {legs.tli_dv():,.0f} m/s, {legs.tli_transfer_days():.1f} days | about 3.1 km/s, 3 to 5 days (textbook) |",
           f"| Arrival speed relative to the Moon | {legs.arrival_vinf():,.0f} m/s | |",
           f"| Capture into 100 km low lunar orbit | {legs.lunar_orbit_insertion_dv():,.0f} m/s | |",
           f"| LLO insertion plus departure | {2*legs.lunar_orbit_insertion_dv():,.0f} m/s | 2,800 m/s with Artemis design factors (cited) |",
           f"| NRHO insertion plus departure | not patched-conic | 1,000 m/s for Orion (cited) |",
           f"| NRHO to LLO | not patched-conic | {TRAJECTORY['nrho_to_llo'].value:.0f} m/s (cited) |",
           f"| Speed at the 100 x 15 km perilune | {legs.perilune_speed():,.0f} m/s | |",
           f"| Earth entry speed from the Moon | {legs.earth_entry_speed():,.0f} m/s | {EARTH_RETURN['artemis2_entry_speed'].value:,.0f} m/s, Artemis II (cited) |",
           f"| Earth entry speed from LEO | {legs.leo_return_entry_speed():,.0f} m/s | |", ""]

    # 2. Apollo validation of the landing simulation
    d, a = apollo_validation()
    L = APOLLO_LM
    md += ["## 2. Landing simulation checked against Apollo", "",
           "| Quantity | Simulation | Apollo (cited capability) |", "| --- | --- | --- |",
           f"| Descent delta-v | {d.total_dv:,.0f} m/s (braking {d.braking_dv:,.0f}, terminal {d.terminal_dv:,.0f}) | {L['descent_dv_capability'].value:,.0f} m/s |",
           f"| Descent propellant | {d.propellant:,.0f} kg | {L['descent_propellant'].value:,.0f} kg loaded |",
           f"| Braking time and range | {d.braking_time:.0f} s, {d.braking_range_km:.0f} km | |",
           f"| Gravity loss on descent | {d.gravity_loss:,.0f} m/s | |",
           f"| Ascent delta-v to 15 x 100 km, then circular | {a.total_dv:,.0f} m/s ({a.dv_to_insertion:,.0f} + {a.circularization_dv:.0f}) | {L['ascent_dv_capability'].value:,.0f} m/s |",
           f"| Ascent propellant | {a.propellant:,.0f} kg | {L['ascent_propellant'].value:,.0f} kg loaded |",
           f"| Ascent burn time | {a.burn_time:.0f} s | |", ""]
    study["apollo"] = {"descent": thin(d.trajectory), "ascent": thin(a.trajectory),
                       "descent_dv": d.total_dv, "ascent_dv": a.total_dv}

    # 3. Architectures
    res = arch.run_all()
    study["architectures"] = {}
    md += ["## 3. Architectures for one crewed landing (4 crew, 10 t cargo down)", "",
           "| Architecture | Closes? | Propellant in LEO | Tanker launches | Heavy launches total |",
           "| --- | --- | --- | --- | --- |"]
    for key in ("A", "B", "C"):
        r = res[key]
        sls = " + 1 SLS" if r.sls_launches else ""
        md.append(f"| {r.name} | {'yes' if r.feasible else 'no'} | {r.propellant_in_leo_t:,.0f} t | "
                  f"{r.tanker_launches} | {r.total_launches}{sls} |")
        study["architectures"][key] = {
            "name": r.name, "feasible": r.feasible, "propellant_t": r.propellant_in_leo_t,
            "tankers": r.tanker_launches, "launches": r.total_launches,
            "burns": [asdict(b) for b in r.burns], "notes": r.notes,
        }
    md.append("")
    for key in ("A", "B", "C"):
        r = res[key]
        md += [f"### {r.name}", ""]
        if r.burns and r.burns[0].isp:
            md += ["| Burn | Delta-v (incl. 5% margin) | Isp | Propellant | Mass before |", "| --- | --- | --- | --- | --- |"]
            md += [f"| {b.name} | {b.dv:,.0f} m/s | {b.isp:.0f} s | {b.propellant_t:,.1f} t | {b.mass_before_t:,.1f} t |"
                   for b in r.burns]
            md.append("")
        md += [f"- {n}" for n in r.notes]
        if r.descent:
            dd, aa = r.descent, r.ascent
            md.append(f"- Simulated descent: {dd.total_dv:,.0f} m/s ({dd.gravity_loss:,.0f} m/s gravity and terminal loss), "
                      f"braking {dd.braking_time:.0f} s over {dd.braking_range_km:.0f} km on one Raptor; ascent {aa.total_dv:,.0f} m/s "
                      f"({aa.gravity_loss:.0f} m/s gravity loss).")
            if not r.feasible and key == "C":
                tk = res["tanker"]
                short = r.propellant_in_leo_t - 1_600
                md.append(f"- Short by {short:,.0f} t. One cislunar tanker delivers {tk.delivered_t:,.0f} t to NRHO "
                          f"({tk.earth_launches} launches), so a lunar-orbit refill makes C close at roughly "
                          f"{r.total_launches + tk.earth_launches} launches.")
            study["architectures"][key]["descent"] = thin(dd.trajectory)
            study["architectures"][key]["ascent"] = thin(aa.trajectory)
        md.append("")

    # 4. Hover check: can a Raptor-powered lander hover?
    sl = size_engine(Vehicle().engine)
    A = res["A"]
    m_land = A.descent.landed_mass
    twr_raptor_min = RAPTOR["throttle_min"].value * sl.thrust_vac / (m_land * legs.G_MOON)
    md += ["## 4. Terminal landing: Raptor alone cannot hover", "",
           f"Architecture A touches down at {m_land/1e3:,.0f} t, a lunar weight of {m_land*legs.G_MOON/1e3:,.0f} kN. "
           f"One Raptor at its cited 40% minimum throttle gives {RAPTOR['throttle_min'].value*sl.thrust_vac/1e3:,.0f} kN, "
           f"a thrust-to-weight of {twr_raptor_min:.2f}. It cannot hover or descend slowly, so the terminal phase "
           "needs either landing thrusters (the HLS approach, cited) or a Raptor that throttles below about "
           f"{100/twr_raptor_min*RAPTOR['throttle_min'].value:.0f}% of full thrust.", ""]
    study["hover"] = {"landed_t": m_land / 1e3, "raptor_min_twr": twr_raptor_min}

    # Braking engine count sweep
    md += ["| Raptors used for braking | Descent delta-v | Gravity and terminal loss | Braking time |", "| --- | --- | --- | --- |"]
    sweep_eng = []
    for n in (1, 2, 3):
        r = arch.nrho_hls(replace(arch.LunarAssumptions(), braking_engines=n))
        sweep_eng.append({"engines": n, "dv": r.descent.total_dv, "loss": r.descent.gravity_loss,
                          "time": r.descent.braking_time, "prop": r.propellant_in_leo_t})
        md.append(f"| {n} | {r.descent.total_dv:,.0f} m/s | {r.descent.gravity_loss:,.0f} m/s | {r.descent.braking_time:.0f} s |")
    study["engine_sweep"] = sweep_eng
    md.append("")

    # 5. Sensitivities for architecture A
    heavy = Vehicle(ship_dry_t=150.0)
    from raptor_sim.mission import vehicle_performance
    p_std = vehicle_performance(Vehicle()).payload_to_leo_t
    p_heavy = vehicle_performance(heavy).payload_to_leo_t
    md += ["## 5. Sensitivity of architecture A", "",
           f"Tanker launches for two vehicle cases: the model as built ({p_std:.0f} t to LEO) and with ship dry mass "
           f"150 t ({p_heavy:.0f} t to LEO).", "",
           f"| Lander dry mass | Propellant in LEO | Closes? | Tankers ({p_std:.0f} t/flight) | Tankers ({p_heavy:.0f} t/flight) |",
           "| --- | --- | --- | --- | --- |"]
    sweep = []
    for dry in (80, 100, 120, 140, 160):
        aa = replace(arch.LunarAssumptions(), hls_dry_t=float(dry))
        r1 = arch.nrho_hls(aa)
        r2 = arch.nrho_hls(aa, heavy)
        sweep.append({"dry_t": dry, "prop_t": r1.propellant_in_leo_t, "tankers_155": r1.tanker_launches,
                      "tankers_105": r2.tanker_launches, "feasible": r1.feasible})
        md.append(f"| {dry} t | {r1.propellant_in_leo_t:,.0f} t | {'yes' if r1.feasible else 'no'} | "
                  f"{r1.tanker_launches} | {r2.tanker_launches} |")
    study["dry_sweep"] = sweep
    md += ["", f"Cited estimates for HLS: {STARSHIP_HLS['tanker_flights_low'].value:.0f} tankers (Musk 2021) "
           "to 16 launches overall (GAO 2021) and 'high teens' (NASA 2023).", ""]

    # Anytime abort
    abort = TRAJECTORY["surface_abort_to_nrho"].value
    r_abort = arch.nrho_hls(replace(arch.LunarAssumptions(), return_staging_dv=abort))
    md += [f"Anytime abort from the surface to NRHO needs up to {abort:,.0f} m/s in space (cited) instead of the "
           f"nominal {TRAJECTORY['nrho_to_llo'].value:.0f} m/s. Sizing the lander for it raises propellant in LEO from "
           f"{A.propellant_in_leo_t:,.0f} t to {r_abort.propellant_in_leo_t:,.0f} t "
           f"({r_abort.tanker_launches} tankers instead of {A.tanker_launches}).", ""]
    study["abort_prop_t"] = r_abort.propellant_in_leo_t

    # 6. Future: reusable lander with lunar ice
    tk = res["tanker"]
    md += ["## 6. Future option: reusable lander refilled with lunar ice", "",
           f"A Starship tanker refilled in LEO delivers {tk.delivered_t:,.0f} t to NRHO and aerobrakes home; filling it "
           f"takes {tk.earth_launches} launches, so every 100 t in NRHO costs {tk.launches_per_100t:.1f} launches.", "",
           "| Variant | Propellant per sortie | From the Moon | From Earth | Launches per sortie for propellant | Icy regolith per sortie (5.6% water) |",
           "| --- | --- | --- | --- | --- | --- |"]
    study["isru"] = {}
    for key, label in (("D_methane", "Methane lander, lunar oxygen for ascent"),
                       ("D_methane_full", "Methane lander, lunar oxygen for the whole round trip"),
                       ("D_hydrolox", "Hydrogen lander, all propellant from ice")):
        r = res[key]
        md.append(f"| {label} | {r.sortie_propellant_t:,.0f} t | {r.from_moon_t:,.0f} t | {r.from_earth_t:,.0f} t | "
                  f"{r.earth_launches_per_sortie:.1f} | {r.ice_regolith_t:,.0f} t |")
        study["isru"][key] = asdict(r)
    md += ["", "Notes:"] + [f"- {n}" for key in ("D_methane", "D_hydrolox") for n in res[key].notes]
    md += ["- Regolith tonnage assumes all water is recovered; the lunar base thread sizes the real plant.",
           "- Crew still reach NRHO on Orion (one SLS) or a crew ship; this table counts only lander propellant.", ""]

    # 7. Surface stays
    from raptor_sim.crewed_lunar.surface import surface_cases, transit_days

    sc = surface_cases()
    md += ["## 7. Crew consumables and radiation by stay length", "",
           f"In-space time {transit_days():.1f} days (two transfers plus one NRHO period for phasing). "
           "Models from `raptor_sim.crew` (life support and radiation).", "",
           "| Case | Surface days | Life support | Consumables and hardware | Mission dose | Share of 600 mSv career limit |",
           "| --- | --- | --- | --- | --- | --- |"]
    md += [f"| {c['case']} | {c['surface_days']:.0f} | {c['loop']} | {c['consumables_t']:.1f} t | {c['dose_msv']:.0f} mSv | "
           f"{100*c['career_fraction']:.0f}% |" for c in sc]
    md.append("")
    study["surface"] = sc

    # 8. Earth return
    er = earth_return_checks()
    md += ["## 8. Earth return at lunar speed", ""] + er["markdown"] + [""]
    study["earth_return"] = er["data"]

    (OUT / "summary.md").write_text("\n".join(md))
    (OUT / "study.json").write_text(json.dumps(study, indent=1, default=float))
    print("\n".join(md))


if __name__ == "__main__":
    main()
